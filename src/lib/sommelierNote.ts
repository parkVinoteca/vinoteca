import type { Language } from '@/i18n'
export function sommelierPersonalLine(lang: Language, score: number | null | undefined) {
 if(typeof score !== 'number') return lang==='ja'
  ? 'お好みはこれから一緒に探していきましょう。召し上がった感想を残していただけるとうれしいです！'
  : '취향은 앞으로 함께 알아가 볼까요? 드신 뒤 솔직한 감상을 남겨주시면 다음 추천에 도움이 됩니다!'
 if(score>=65) return lang==='ja'
  ? 'これまで比較的高く評価されたスタイルに近く、お好みに合いそうです。ぜひ候補に入れてみてください！'
  : '지금까지 상대적으로 높게 평가하신 스타일과 가까워 손님 취향에 맞을 것 같아요. 다음 한 병의 후보로 추천드립니다!'
 if(score<=35) return lang==='ja'
  ? 'ただ、以前低く評価されたスタイルにも近いので、お好みは分かれるかもしれません。新しい味に挑戦するなら、まず一杯からいかがでしょう？'
  : '다만 이전에 낮게 평가하신 스타일과도 가까워 취향에는 안 맞을 수 있어요. 새로운 맛에 도전하고 싶다면 우선 한 잔부터 어떠세요?'
 return lang==='ja'
  ? '好きだったワインとも、苦手だったワインとも共通点がありますね。まずは一杯、ゆっくり確かめてみませんか？'
  : '좋아하셨던 와인과 아쉬웠던 와인 양쪽에 닮은 점이 있네요. 우선 한 잔으로 천천히 취향을 확인해보면 어떨까요?'
}
